# --------------------------------------------------------------------------
# PAC checking (pure logic, no nameserver needed)
# --------------------------------------------------------------------------
def pac_decision(host: str, hosts: Sequence[str] = GATED_HOSTS) -> str:
    host = host.lower().rstrip(".")
    for gated in hosts:
        if host == gated or host.endswith("." + gated):
            return "PROXY"
    return "DIRECT"


# --------------------------------------------------------------------------
# local proxy: CONNECT (HTTP) or SOCKS5 upstream, no TLS interception
# --------------------------------------------------------------------------
class UpstreamError(Exception):
    pass


def _parse_upstream(spec: str) -> Tuple[str, str, int]:
    """``socks://host:port`` / ``http://host:port`` / ``host:port`` -> (kind, host, port)."""
    spec = spec.strip()
    kind = "http"
    if "://" in spec:
        scheme, _, spec = spec.partition("://")
        scheme = scheme.lower()
        if scheme in ("socks", "socks5", "socks5h"):
            kind = "socks5"
        elif scheme in ("http", "https"):
            kind = "http"
        else:
            raise UpstreamError(f"unsupported upstream scheme {scheme!r}")
    host, _, port_s = spec.rpartition(":")
    if not host or not port_s.isdigit():
        raise UpstreamError(f"bad upstream {spec!r} (expected host:port)")
    return kind, host, int(port_s)


async def _connect_http(upstream: Tuple[str, int], target: Tuple[str, int]) -> Tuple[asyncio.StreamReader, asyncio.StreamWriter]:
    reader, writer = await asyncio.open_connection(*upstream)
    host, port = target
    request = f"CONNECT {host}:{port} HTTP/1.1\r\nHost: {host}:{port}\r\n\r\n"
    writer.write(request.encode("ascii"))
    await writer.drain()
    status = await reader.readline()
    if not status.startswith(b"HTTP/1."):
        writer.close()
        raise UpstreamError(f"bad CONNECT reply: {status!r}")
    code = status.split()[1:2]
    if not code or not code[0].startswith(b"2"):
        writer.close()
        raise UpstreamError(f"upstream refused CONNECT: {status!r}")
    while True:  # headers
        line = await reader.readline()
        if line in (b"\r\n", b"\n", b""):
            break
    return reader, writer


async def _connect_socks5(upstream: Tuple[str, int], target: Tuple[str, int]) -> Tuple[asyncio.StreamReader, asyncio.StreamWriter]:
    reader, writer = await asyncio.open_connection(*upstream)
    writer.write(b"\x05\x01\x00")  # no auth
    await writer.drain()
    greeting = await reader.readexactly(2)
    if greeting != b"\x05\x00":
        writer.close()
        raise UpstreamError(f"upstream refused socks5 no-auth: {greeting!r}")

    host, port = target
    try:
        packed = bytes([1]) + bytes(int(x) for x in host.split("."))  # ATYP 1 = IPv4
        atyp = 1
    except (ValueError, IndexError):
        encoded = host.encode("idna")
        packed = bytes([3, len(encoded)]) + encoded  # ATYP 3 = domain
        atyp = 3
    writer.write(b"\x05\x01\x00" + packed + struct.pack(">H", port))
    await writer.drain()

    reply = await reader.readexactly(4)
    if reply[0] != 5 or reply[1] != 0:
        writer.close()
        raise UpstreamError(f"socks5 connect failed: code={reply[1] if len(reply) > 1 else '?'}")
    atyp_reply = reply[3]
    if atyp_reply == 1:
        await reader.readexactly(4)
    elif atyp_reply == 3:
        length = (await reader.readexactly(1))[0]
        await reader.readexactly(length)
    elif atyp_reply == 4:
        await reader.readexactly(16)
    await reader.readexactly(2)  # port
    return reader, writer


async def _pipe(client: asyncio.StreamReader, client_w: asyncio.StreamWriter,
                upstream: asyncio.StreamReader, upstream_w: asyncio.StreamWriter) -> None:
    async def pump(src, dst):
        try:
            while True:
                chunk = await src.read(65536)
                if not chunk:
                    break
                dst.write(chunk)
                await dst.drain()
        except (ConnectionError, asyncio.IncompleteReadError):
            pass
        finally:
            try:
                dst.close()
            except Exception:
                pass

    await asyncio.gather(pump(client, upstream_w), pump(upstream, client_w))


async def _handle_client(reader: asyncio.StreamReader, writer: asyncio.StreamWriter,
                         upstream_spec: str, log, allow_hosts: Optional[Sequence[str]]) -> None:
    try:
        request_line = await asyncio.wait_for(reader.readline(), timeout=15)
        if not request_line:
            return
        parts = request_line.split()
        if len(parts) < 2 or parts[0].upper() != b"CONNECT":
            writer.write(b"HTTP/1.1 405 Method Not Allowed\r\n\r\n")
            await writer.drain()
            return
        host_port = parts[1].decode("ascii", "replace")
        host, _, port_s = host_port.rpartition(":")
        if not host or not port_s.isdigit():
            writer.write(b"HTTP/1.1 400 Bad Request\r\n\r\n")
            await writer.drain()
            return
        if allow_hosts is not None and pac_decision(host, allow_hosts) != "PROXY":
            # Refusing here is a safety feature, not a limitation: sign-in,
            # OAuth and history sync must never leave through the egress.
            log(f"refused {host_port} (not in allowlist)")
            writer.write(b"HTTP/1.1 403 Forbidden\r\n\r\n")
            await writer.drain()
            return
        target = (host, int(port_s))
        kind, up_host, up_port = _parse_upstream(upstream_spec)

        while True:  # skip remaining request headers
            line = await reader.readline()
            if line in (b"\r\n", b"\n", b""):
                break

        try:
            if kind == "socks5":
                up_r, up_w = await _connect_socks5((up_host, up_port), target)
            else:
                up_r, up_w = await _connect_http((up_host, up_port), target)
        except (OSError, UpstreamError) as exc:
            log(f"upstream failed for {host_port}: {exc}")
            writer.write(b"HTTP/1.1 502 Bad Gateway\r\n\r\n")
            await writer.drain()
            return

        writer.write(b"HTTP/1.1 200 Connection Established\r\n\r\n")
        await writer.drain()
        log(f"tunnel {host_port}")
        await _pipe(reader, writer, up_r, up_w)
    except (asyncio.TimeoutError, ConnectionError):
        pass
    finally:
        try:
            writer.close()
        except Exception:
            pass


async def serve(listen: str, upstream: str, log,
                allow_hosts: Optional[Sequence[str]] = GATED_HOSTS) -> None:
    host, _, port_s = listen.rpartition(":")
    server = await asyncio.start_server(
        lambda r, w: _handle_client(r, w, upstream, log, allow_hosts),
        host or "127.0.0.1",
        int(port_s),
    )
    addrs = ", ".join(str(s.getsockname()) for s in server.sockets or [])
    if allow_hosts is None:
        scope = "ALL hosts (no allowlist)"
    else:
        scope = "only: " + ", ".join(allow_hosts)
    log(f"listening on {addrs} -> {upstream}")
    log(f"CONNECT only, no TLS interception; forwarding {scope}")
    async with server:
        await server.serve_forever()
